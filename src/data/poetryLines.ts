/**
 * Returns a randomly chosen poetry line from the collection.
 * Optionally avoids repeating the quote at `excludeIndex`.
 */
export function getRandomPoetryLine(excludeIndex?: number): { quote: PoetryQuote; index: number } {
  if (POETRY_LINES.length === 0) {
    throw new Error("No poetry lines available");
  }
  if (POETRY_LINES.length === 1) {
    return { quote: POETRY_LINES[0], index: 0 };
  }

  let index = Math.floor(Math.random() * POETRY_LINES.length);
  if (typeof excludeIndex === "number" && index === excludeIndex) {
    index =
      (index + 1 + Math.floor(Math.random() * (POETRY_LINES.length - 1))) % POETRY_LINES.length;
  }

  return { quote: POETRY_LINES[index], index };
}
